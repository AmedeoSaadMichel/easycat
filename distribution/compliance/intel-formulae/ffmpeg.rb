class Ffmpeg < Formula
  env :std # Reuse explicitly pinned Intel runtime and hosted build tools.
  desc "Play, record, convert, and stream select audio and video codecs"
  homepage "https://ffmpeg.org/"
  url "https://ffmpeg.org/releases/ffmpeg-9.0.2.tar.xz"
  sha256 "8c3850283eb25fa026482078a04051e0be17347b09ef81a0849bec15a96e002e"
  # None of these parts are used by default, you have to explicitly pass `--enable-gpl`
  # to configure to activate them. In this case, FFmpeg's license changes to GPL v2+.
  # Passing `--enable-version3` changes the license to GPL v3+.
  license "GPL-3.0-or-later"
  revision 1
  compatibility_version 3
  head "https://github.com/FFmpeg/FFmpeg.git", branch: "master"

  livecheck do
    url "https://ffmpeg.org/download.html"
    regex(/href=.*?ffmpeg[._-]v?(\d+(?:\.\d+)+)\.t/i)
  end

  depends_on "pkgconf" => :build

  # Only add dependencies required for dependents in homebrew-core
  # or INCREDIBLY widely used and light codecs in the current year (2026).
  # Add other dependencies to ffmpeg-full formula.
  # We should expect to remove e.g. x264 eventually (>=2027) when usage of it is
  # negligible and has all moved to e.g. x265 instead.
  depends_on "dav1d"
  depends_on "lame"
  depends_on "libvmaf" # dependent: ab-av1
  depends_on "libvpx"
  depends_on "openssl@4"
  depends_on "opus"
  depends_on "sdl2-compat"
  depends_on "svt-av1"
  depends_on "x264"
  depends_on "x265"
  depends_on "xz"

  uses_from_macos "bzip2"
  uses_from_macos "libxml2"

  on_linux do
    depends_on "alsa-lib"
    depends_on "libxcb"
    depends_on "zlib-ng-compat"
  end

  on_intel do
    depends_on "nasm" => :build
  end

  deny_network_access!

  def install
    ENV.delete("CPATH") # Let the selected SDK order C++ and C headers correctly.
    # The new linker leads to duplicate symbol issue https://github.com/homebrew-ffmpeg/homebrew-ffmpeg/issues/140
    ENV.append "LDFLAGS", "-Wl,-ld_classic" if DevelopmentTools.ld64_version.between?("1015.7", "1022.1")

    # Fine adding any new options that don't add dependencies to the formula.
    args = %W[
      --prefix=#{prefix}
      --enable-shared
      --enable-pthreads
      --enable-version3
      --cc=#{ENV.cc}
      --host-cflags=#{ENV.cflags}
      --host-ldflags=#{ENV.ldflags}
      --enable-ffplay
      --enable-gpl
      --enable-libsvtav1
      --enable-libopus
      --enable-libx264
      --enable-libmp3lame
      --enable-libdav1d
      --enable-libvmaf
      --enable-libvpx
      --enable-libx265
      --enable-openssl
    ]

    # Standard SDK builds must prefer the pinned dependencies over runner libraries.
    runtime_deps = deps.reject(&:build?)
    include_flags = runtime_deps.map { |dep| "-I#{HOMEBREW_PREFIX}/opt/#{dep.name}/include" }.join(" ")
    library_flags = runtime_deps.map { |dep| "-L#{HOMEBREW_PREFIX}/opt/#{dep.name}/lib" }.join(" ")
    pkg_config_dirs = runtime_deps.flat_map do |dep|
      %W[#{HOMEBREW_PREFIX}/opt/#{dep.name}/lib/pkgconfig #{HOMEBREW_PREFIX}/opt/#{dep.name}/share/pkgconfig]
    end.join(":")
    ENV["PKG_CONFIG_PATH"] = pkg_config_dirs
    ENV["PKG_CONFIG_LIBDIR"] = pkg_config_dirs
    ENV.prepend "CPPFLAGS", include_flags
    ENV.prepend "LDFLAGS", library_flags
    args << "--extra-cflags=#{include_flags}"
    args << "--extra-ldflags=#{library_flags}"
    args += %w[--disable-xlib --disable-libxcb]

    # Needs corefoundation, coremedia, corevideo
    args += %w[--enable-videotoolbox --enable-audiotoolbox] if OS.mac?
    args << "--enable-neon" if Hardware::CPU.arm?

    begin
      system "./configure", *args
    ensure
      config_log = buildpath/"ffbuild/config.log"
      cp config_log, logs/"ffmpeg-config.log" if config_log.exist?
    end
    system "make", "install"

    # Build and install additional FFmpeg tools
    system "make", "alltools"
    bin.install (buildpath/"tools").children.select { |f| f.file? && f.executable? }
    pkgshare.install buildpath/"tools/python"
  end

  def caveats
    <<~EOS
      ffmpeg-full includes additional tools and libraries that are not included in the regular ffmpeg formula.
    EOS
  end

  test do
    # Create a 5 second test MP4
    mp4out = testpath/"video.mp4"
    system bin/"ffmpeg", "-filter_complex", "testsrc=rate=1:duration=5", mp4out
    assert_path_exists mp4out, "Failed to create video.mp4!"
  end
end
